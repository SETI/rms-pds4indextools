"""The three programmatic ``run_*`` entry points and their pipeline helpers.

Each ``run_*`` function drives a full subcommand pipeline: bundle-root and
pattern validation (R-CLI-010..R-CLI-011, R-FS-001..R-FS-004), config-chain
loading (R-CFG-051), schema-type resolution, per-label scraping with
fail-slow accumulation (R-FSLOW-110), and atomic output writing (R-ERR-002).
The functions raise :class:`~pds4indextools.errors.Pds4IndexError` subclasses
on failure (R-API-004); the CLI dispatcher maps those to exit codes.

Implements spec section 4 (R-IDX-*), section 5, section 6, section 17.3
(R-FSLOW-*), and section 20 (R-API-*).
"""

